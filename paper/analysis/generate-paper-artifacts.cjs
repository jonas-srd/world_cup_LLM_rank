/**
 * Purpose: Reproducible generator for LLM-SoccerArena paper artifacts.
 *
 * Reads the live benchmark SQLite database and emits paper-ready, self-contained
 * LaTeX fragments (numeric macros, booktabs tables, and pgfplots figures) plus
 * the underlying CSV data for full transparency. The paper \input{}s the LaTeX
 * fragments; no external plotting toolchain is required (pgfplots renders on
 * compile).
 *
 * Usage:
 *   node paper/analysis/generate-paper-artifacts.cjs \
 *     --db=data/world-cup.db \
 *     --out=<overleaf-project>/generated \
 *     --csv=paper/artifacts
 *
 * All outputs are pre-outcome diagnostics: they describe stored predictions and
 * operational behaviour, NOT forecast accuracy (no match has finished yet).
 */
const Database = require("better-sqlite3");
const { mkdirSync, writeFileSync } = require("node:fs");
const { resolve, join } = require("node:path");

function parseArg(name, fallback) {
  const prefix = `--${name}=`;
  const hit = process.argv.find((a) => a.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : fallback;
}

const DB_PATH = resolve(parseArg("db", "data/world-cup.db"));
const OUT_DIR = resolve(parseArg("out", "paper/generated"));
const CSV_DIR = resolve(parseArg("csv", "paper/artifacts"));

mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(CSV_DIR, { recursive: true });

const db = new Database(DB_PATH, { readonly: true });

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
const get = (sql, p = {}) => db.prepare(sql).get(p);
const all = (sql, p = {}) => db.prepare(sql).all(p);
const pct = (num, den) => (den === 0 ? 0 : (100 * num) / den);
const r0 = (x) => `${Math.round(x)}`;
const r1 = (x) => (Math.round(x * 10) / 10).toFixed(1);
const r2 = (x) => (Math.round(x * 100) / 100).toFixed(2);
const r3 = (x) => (Math.round(x * 1000) / 1000).toFixed(3);
const texEsc = (s) => String(s).replace(/_/g, "\\_").replace(/&/g, "\\&");

function writeOut(name, content) {
  writeFileSync(join(OUT_DIR, name), content, "utf8");
  console.log("wrote", join(OUT_DIR, name));
}
function writeCsv(name, rows) {
  if (rows.length === 0) return;
  const cols = Object.keys(rows[0]);
  const lines = [cols.join(",")];
  for (const row of rows) lines.push(cols.map((c) => row[c]).join(","));
  writeFileSync(join(CSV_DIR, name), lines.join("\n"), "utf8");
  console.log("wrote", join(CSV_DIR, name));
}

